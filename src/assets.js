  ctx.quadraticCurveTo(-38, -6, -22, -14);
  ctx.lineTo(22, -14);
  ctx.quadraticCurveTo(38, -6, 30, 34);
  ctx.closePath();
  ctx.fill();
  // head
  ctx.fillStyle = '#8fbf63';
  ctx.beginPath();
  ctx.ellipse(0, -22, 26, 22, 0, 0, Math.PI * 2);
  ctx.fill();
  // ears
  ctx.beginPath();
  ctx.moveTo(-24, -30);
  ctx.lineTo(-50, -46);
  ctx.lineTo(-24, -12);
  ctx.closePath();
  ctx.fill();
  ctx.beginPath();
  ctx.moveTo(24, -30);
  ctx.lineTo(50, -46);
  ctx.lineTo(24, -12);
  ctx.closePath();
  ctx.fill();
  // eyes
  ctx.fillStyle = '#1b1b1b';
  const eyeY = state === 'spent' ? -18 : -24;
  ctx.beginPath();
  ctx.arc(-9, eyeY, 4.5, 0, Math.PI * 2);
  ctx.arc(9, eyeY, 4.5, 0, Math.PI * 2);
