function drawRock(ctx, r, fill, edge) {
  ctx.fillStyle = fill;
  ctx.strokeStyle = edge;
  ctx.lineWidth = 3;
  ctx.beginPath();
  const n = 9;
  for (let i = 0; i < n; i++) {
    const a = (Math.PI * 2 * i) / n;
    const wobble = 0.72 + Math.random() * 0.0; // stable silhouette handled below
    const rr = r * (0.82 + ((i * 37) % 20) / 100);
    const px = Math.cos(a) * rr;
    const py = Math.sin(a) * rr;
    if (i === 0) ctx.moveTo(px, py);
    else ctx.lineTo(px, py);
    void wobble;
  }
  ctx.closePath();
  ctx.fill();
  ctx.stroke();
  ctx.fillStyle = 'rgba(0,0,0,0.18)';
  ctx.beginPath();
  ctx.arc(-r * 0.2, r * 0.15, r * 0.35, 0, Math.PI * 2);
  ctx.fill();
}

