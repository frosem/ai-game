// Per-sprite on-screen multiplier so the hand-drawn pixel art lands at the
// right size relative to each entity's hit radius. Call sites still pass their
// own scale; this is an additional base factor baked in here.
const BASE_SCALE = {
  player_xwing_force: 1.15,
  convoy_ship: 1.5,
  enemy_gunship: 1.4,
  enemy_lancer: 1.55,
  asteroid_s: 2,
  asteroid_m: 2,
  asteroid_l: 2,
  portrait_grogu: 1.4,
  portrait_grogu_tired: 1.4,
  portrait_grogu_spent: 1.4,
  portrait_mando: 1.4,
  portrait_luke: 1.4,
};

const images = new Map();

export function loadAssets() {
  return Promise.all(
    MANIFEST.map(
      (key) =>
        new Promise((resolve) => {
          const img = new Image();
          img.onload = () => {
            // 1x1 transparent sentinel files ship by default; real teammate art
            // is larger and replaces the procedural placeholder. Missing files
            // also degrade to the placeholder, never a crash.
            if (img.naturalWidth > 1 && img.naturalHeight > 1) {
              images.set(key, img);
            }
            resolve();
          };
          img.onerror = () => resolve();
          img.src = `./assets/${key}.png`;
        })
    )
  ).then(() => {
    // Asteroids have no teammate art yet: build crisp pixel-art rocks so they
    // match the hand-drawn sprites instead of the smooth vector placeholder.
    for (const [key, n, seed] of [
      ['asteroid_s', 18, 7],
      ['asteroid_m', 34, 23],
      ['asteroid_l', 56, 41],
    ]) {
      if (!images.has(key)) images.set(key, makeAsteroid(n, seed));
    }
  });
}

// Deterministic blocky asteroid. One canvas pixel == one art pixel; BASE_SCALE
// doubles it so every "pixel" is a clean 2x2 square on screen.
function makeAsteroid(n, seed) {
  const c = document.createElement('canvas');
  c.width = n;
  c.height = n;
  const g = c.getContext('2d');
  let s = seed >>> 0;
  const rnd = () => (s = (s * 1664525 + 1013904223) >>> 0) / 4294967296;
  const cx = (n - 1) / 2;
  const cy = (n - 1) / 2;
  const R = n * 0.46;
  const base = '#8a8577';
  const dark = '#5d594e';
  const edge = '#4f4b42';
  const lite = '#a49d8b';
  const lobes = 7;
  const amp = Array.from({ length: lobes }, () => 0.10 + rnd() * 0.20);
  for (let y = 0; y < n; y++) {
    for (let x = 0; x < n; x++) {
      const dx = (x - cx) / R;
      const dy = (y - cy) / R;
      const dist = Math.hypot(dx, dy);
      const ang = Math.atan2(dy, dx);
      let lim = 1;
      for (let k = 0; k < lobes; k++) lim += Math.cos(ang * (k + 1) + seed) * amp[k] * 0.32;
      if (dist <= lim) {
        let col = base;
        if (dist > lim - 0.18) col = edge;
        else if (-dx * 0.4 - dy * 0.4 > 0.15) col = lite;
        if (rnd() < 0.10) col = dark;
        g.fillStyle = col;
        g.fillRect(x, y, 1, 1);
      }
    }
  }
  const craters = 2 + Math.floor(rnd() * 2);
  for (let i = 0; i < craters; i++) {
    const a = rnd() * Math.PI * 2;
    const d = rnd() * 0.5;
    const px = cx + Math.cos(a) * d * R;
    const py = cy + Math.sin(a) * d * R;
    const cr = 1.5 + rnd() * 2.5;
    for (let y = Math.floor(py - cr - 1); y <= py + cr + 1; y++) {
      for (let x = Math.floor(px - cr - 1); x <= px + cr + 1; x++) {
        if (x < 0 || y < 0 || x >= n || y >= n) continue;
        const dd = Math.hypot(x - px, y - py);
        if (dd <= cr) {
          g.fillStyle = dark;
          g.fillRect(x, y, 1, 1);
        } else if (dd <= cr + 1) {
          g.fillStyle = edge;
          g.fillRect(x, y, 1, 1);
        }
      }
    }
  }
  return c;
}

// Raw Image/Canvas backing a loaded asset, for callers that need custom
// drawing (tiled backdrops, sprite-strip frames) instead of drawSprite's
// single centered blit.
export function getImage(key) {
  return images.get(key);
}

// Animation strips generated by project-sw are always square frames laid out
// left to right, frame size == strip height. No frame metadata needed.
export function stripFrameCount(key) {
  const img = images.get(key);
  if (!img) return 0;
  return Math.max(1, Math.round(img.width / img.height));
}

// Draws one frame of a strip, centered at (x, y). Returns false (drawing
// nothing) if the strip failed to load, so callers can skip gracefully.
export function drawStripFrame(key, ctx, x, y, frame, scale = 1, angle = 0) {
  const img = images.get(key);
  if (!img) return false;
  const size = img.height;
  const count = Math.max(1, Math.round(img.width / size));
  const f = ((Math.floor(frame) % count) + count) % count;
  ctx.save();
  ctx.translate(x, y);
  if (angle) ctx.rotate(angle);
  const d = size * scale;
  ctx.drawImage(img, f * size, 0, size, size, -d / 2, -d / 2, d, d);
  ctx.restore();
  return true;
}

export function drawSprite(key, ctx, x, y, angle = 0, scale = 1) {
  const img = images.get(key);
  const s = scale * (BASE_SCALE[key] || 1);
  ctx.save();
  ctx.translate(x, y);
  if (angle) ctx.rotate(angle);
  if (s !== 1) ctx.scale(s, s);
  if (img) {
    ctx.drawImage(img, -img.width / 2, -img.height / 2);
  } else {
    drawPlaceholder(key, ctx);
  }
  ctx.restore();
}

