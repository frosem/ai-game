function drawPlaceholder(key, ctx) {
  switch (key) {
    case 'player_xwing':
    case 'player_xwing_force':
      drawXwing(ctx);
      break;
    case 'convoy_ship':
      drawRazorCrest(ctx);
      break;
    case 'enemy_interceptor':
      drawInterceptor(ctx);
      break;
    case 'enemy_gunship':
      drawGunship(ctx);
      break;
    case 'enemy_lancer':
      drawLancer(ctx);
      break;
    case 'asteroid_s':
      drawRock(ctx, 18, '#8a8577', '#5d594e');
      break;
    case 'asteroid_m':
      drawRock(ctx, 34, '#8a8577', '#5d594e');
      break;
    case 'asteroid_l':
      drawRock(ctx, 56, '#7d786b', '#4f4b42');
      break;
    case 'portrait_grogu':
      drawGrogu(ctx, 'ok');
      break;
    case 'portrait_grogu_tired':
      drawGrogu(ctx, 'tired');
      break;
    case 'portrait_grogu_spent':
      drawGrogu(ctx, 'spent');
      break;
    case 'portrait_mando':
      drawMando(ctx);
      break;
    case 'portrait_luke':
      drawLuke(ctx);
      break;
    default:
      drawFallback(ctx);
  }
}

